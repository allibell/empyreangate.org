/**
 * Web renditions of the photos.
 *
 * Originals live in `photos/` and are committed: there won't be many, and the
 * repo is the one place everyone has. This turns each one into WebP at a few
 * widths plus a JPEG fallback under `public/photos/` (gitignored, rebuilt on
 * every build, including on Cloudflare), and writes
 * `app/content/photo-manifest.ts` with the dimensions the layout needs.
 *
 * EXIF is dropped on the way through, including GPS. Orientation is applied
 * first, so a portrait phone shot stays portrait.
 *
 *   bun run photos           # anything new or changed
 *   bun run photos --force   # everything
 */

import { mkdir, readdir, stat, writeFile } from "node:fs/promises";
import { basename, extname, join } from "node:path";
import sharp from "sharp";

const SRC = "photos";
const OUT = "public/photos";
const MANIFEST = "app/content/photo-manifest.ts";
const WIDTHS = [800, 1600, 2400];
const JPEG_WIDTH = 1600;
const INPUT = new Set([".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff"]);

const force = process.argv.includes("--force");

interface Rendition {
  width: number;
  height: number;
  widths: number[];
  jpg: number;
}

/** "IMG 1234 (final).JPG" -> "img-1234-final" */
function slug(file: string): string {
  return basename(file, extname(file))
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function newer(a: string, b: string): Promise<boolean> {
  try {
    const [sa, sb] = await Promise.all([stat(a), stat(b)]);
    return sa.mtimeMs > sb.mtimeMs;
  } catch {
    return true;
  }
}

await mkdir(SRC, { recursive: true });
await mkdir(OUT, { recursive: true });

const files = (await readdir(SRC))
  .filter((f) => INPUT.has(extname(f).toLowerCase()))
  .sort((a, b) => a.localeCompare(b));

const manifest: Record<string, Rendition> = {};
const seen = new Map<string, string>();

for (const file of files) {
  const name = slug(file);
  const clash = seen.get(name);
  if (clash) {
    throw new Error(`${file} and ${clash} both become "${name}"; rename one`);
  }
  seen.set(name, file);

  const src = join(SRC, file);
  const image = sharp(src).rotate();
  const meta = await image.metadata();
  const srcWidth = meta.width ?? 0;
  const srcHeight = meta.height ?? 0;
  if (!srcWidth || !srcHeight) throw new Error(`${file}: no dimensions`);

  // Never upscale: widths beyond the original collapse to the original.
  const widths = [...new Set(WIDTHS.map((w) => Math.min(w, srcWidth)))];
  const jpg = Math.min(JPEG_WIDTH, srcWidth);

  let largest = { width: 0, height: 0 };
  for (const w of widths) {
    const out = join(OUT, `${name}-${w}.webp`);
    if (force || (await newer(src, out))) {
      const info = await image
        .clone()
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: 82 })
        .toFile(out);
      if (info.width > largest.width) largest = info;
      console.log(`${out}  ${info.width}x${info.height}`);
    } else {
      const info = await sharp(out).metadata();
      if ((info.width ?? 0) > largest.width) {
        largest = { width: info.width ?? 0, height: info.height ?? 0 };
      }
    }
  }
  const jpgOut = join(OUT, `${name}-${jpg}.jpg`);
  if (force || (await newer(src, jpgOut))) {
    await image
      .clone()
      .resize({ width: jpg, withoutEnlargement: true })
      .jpeg({ quality: 84, mozjpeg: true })
      .toFile(jpgOut);
    console.log(jpgOut);
  }

  manifest[name] = { ...largest, widths, jpg };
}

const body = Object.entries(manifest)
  .map(
    ([name, r]) =>
      `  "${name}": { width: ${r.width}, height: ${r.height}, widths: [${r.widths.join(", ")}], jpg: ${r.jpg} },`,
  )
  .join("\n");

await writeFile(
  MANIFEST,
  [
    "// Generated by scripts/photos.ts from photos/. Do not edit; run `bun run photos`.",
    'import type { PhotoAsset } from "./gallery";',
    "",
    // `{}` when empty, so a build with no photos leaves the committed file as-is.
    ...(body
      ? [
          "export const PHOTO_MANIFEST: Record<string, PhotoAsset> = {",
          body,
          "};",
        ]
      : ["export const PHOTO_MANIFEST: Record<string, PhotoAsset> = {};"]),
    "",
  ].join("\n"),
  "utf8",
);
console.log(`${files.length} photo(s); wrote ${MANIFEST}`);
